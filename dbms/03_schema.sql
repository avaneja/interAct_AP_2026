-- InterAct - CP2 Database Schema
-- PostgreSQL

BEGIN;

-- 1. Users
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT,
    auth_provider VARCHAR(50),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Documents
CREATE TABLE documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    file_name VARCHAR(255) NOT NULL,
    file_type VARCHAR(20) NOT NULL,
    storage_path TEXT NOT NULL,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Document chunks
CREATE TABLE document_chunks (
    chunk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(document_id)
        ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    chunk_text TEXT NOT NULL,
    UNIQUE (document_id, chunk_index)
);

-- 4. Document topics
CREATE TABLE document_topics (
    document_id BIGINT NOT NULL REFERENCES documents(document_id)
        ON DELETE CASCADE,
    topic_name VARCHAR(200) NOT NULL,
    PRIMARY KEY (document_id, topic_name)
);

-- 5. Sessions
CREATE TABLE sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    document_id BIGINT REFERENCES documents(document_id)
        ON DELETE SET NULL,
    topic_name VARCHAR(200),
    difficulty VARCHAR(30) NOT NULL,
    interview_style VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);

-- 6. Preparation messages
CREATE TABLE preparation_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions(session_id)
        ON DELETE CASCADE,
    role VARCHAR(30) NOT NULL,
    message_text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Rubrics
CREATE TABLE rubrics (
    rubric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rubric_name VARCHAR(150) NOT NULL,
    description TEXT
);

-- 8. Questions
CREATE TABLE questions (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rubric_id BIGINT REFERENCES rubrics(rubric_id),
    question_text TEXT NOT NULL,
    difficulty VARCHAR(30),
    question_type VARCHAR(50)
);

-- 9. Answers
CREATE TABLE answers (
    session_id BIGINT NOT NULL REFERENCES sessions(session_id)
        ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(question_id),
    answer_text TEXT NOT NULL,
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id, question_id)
);

-- 10. Evaluations
CREATE TABLE evaluations (
    session_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    score NUMERIC(5,2),
    feedback TEXT,
    evaluated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id, question_id),
    FOREIGN KEY (session_id, question_id)
        REFERENCES answers(session_id, question_id)
        ON DELETE CASCADE,
    CHECK (score IS NULL OR (score >= 0 AND score <= 100))
);

-- 11. Reports
CREATE TABLE reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL UNIQUE REFERENCES sessions(session_id)
        ON DELETE CASCADE,
    overall_score NUMERIC(5,2),
    summary TEXT,
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        overall_score IS NULL OR
        (overall_score >= 0 AND overall_score <= 100)
    )
);

-- 12. Jobs
CREATE TABLE jobs (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    job_type VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP
);

-- 13. LLM calls
CREATE TABLE llm_calls (
    llm_call_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT REFERENCES jobs(job_id) ON DELETE SET NULL,
    session_id BIGINT REFERENCES sessions(session_id)
        ON DELETE SET NULL,
    operation VARCHAR(100) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    input_tokens INTEGER CHECK (input_tokens IS NULL OR input_tokens >= 0),
    output_tokens INTEGER CHECK (output_tokens IS NULL OR output_tokens >= 0),
    latency_ms NUMERIC(12,2)
        CHECK (latency_ms IS NULL OR latency_ms >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 14. Experiment runs
CREATE TABLE experiment_runs (
    experiment_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_name VARCHAR(200) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    prompt_version VARCHAR(100),
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP
);

COMMIT;
